"""Writes xob.meta + prefabs for the destructible mosque windows and rewrites Mosque_01.et (hall prefab) with window instances.
usage: python mosque_windows_prefabs.py panes.json   (run from the addon root). GUIDs are generated once and kept in Docs/blender/windows_guids.json."""
import json, os, random, re, sys
ROOT = "Prefabs/Structures/Mosque_01"; WIN = ROOT + "/Windows"
GFILE = "Docs/blender/windows_guids.json"
guids = json.load(open(GFILE)) if os.path.exists(GFILE) else {}
rng = random.Random(4711)
def h(): return "".join(rng.choice("0123456789ABCDEF") for _ in range(16))
def G(key):
    if key not in guids: guids[key] = h()
    return guids[key]
GLASS_EMAT = "{0A11BCBCE1D63AB2}Assets/Structures/BuildingsParts/Windows/Data/window_glass_uneven_EXT.emat"
FRAME_EMAT = "{5D11FDD2580C842A}Prefabs/Structures/Mosque_01/Panes/Data/Mosque_01_PaneFrame.emat"
tmpl = open(ROOT + "/Panes/Pane_Body.xob.meta", encoding="utf-8").read()

def xob_meta(base, src_mat, emat):
    mp = '%s/%s.xob.meta' % (WIN, base)
    if os.path.exists(mp):      # Workbench generated it (ExportFBXResource): keep its GUID, only fix the material assignment
        t = open(mp, encoding='utf-8').read(); guids[base + '.xob'] = re.search(r'Name "\{([0-9A-F]{16})\}', t).group(1)
        t = re.sub(r'AssignedMaterial "[^"]*"', 'AssignedMaterial "%s"' % emat, t); open(mp, 'w', newline='\n').write(t); return
    t = tmpl.replace("{5276EAB3D29C2206}Prefabs/Structures/Mosque_01/Panes/Pane_Body.xob", "{%s}%s/%s.xob" % (G(base + '.xob'), WIN, base))
    a = t.index("   MaterialAssigns {"); b = t.index("   MeshParams {")
    t = t[:a] + '   MaterialAssigns {\n    MaterialAssignClass "{%s}" {\n     SourceMaterial "%s"\n     AssignedMaterial "%s"\n    }\n   }\n' % (G(base + '.ma'), src_mat, emat) + t[b:]
    t = t.replace("MeshParam Pane_Body", "MeshParam " + base).replace("UTM_Pane_Body", "UTM_" + base)
    for i, old in enumerate(["6AB17DCA4CB27695", "6AB17DCA4CB27748", "6AB17DCA4CB27711", "6AB17DCA4CB274E1", "6AB17DCA4CB274B4", "6AB17DCA4CB27491", "6AB17DCA4CB27467"]):
        t = t.replace(old, G(base + '.tx%d' % i))
    open("%s/%s.xob.meta" % (WIN, base), "w", newline="\n").write(t)

def et_meta(path, key):
    t = open("Prefabs/Structures/BuildingParts/Windows/Glass_ChurchSmall_E/Glass_ChurchSmall_E_74x159_01_mosque.et.meta", encoding="utf-8").read()
    t = t.replace("{79E277734BA2ACB8}Prefabs/Structures/BuildingParts/Windows/Glass_ChurchSmall_E/Glass_ChurchSmall_E_74x159_01_mosque.et", "{%s}%s" % (G(key), path))
    open(path + ".meta", "w", newline="\n").write(t)

for kind in ("Body", "Drum"):
    xob_meta(f"Win_Mosque_{kind}", "Mosque_01_PaneFrame", FRAME_EMAT)
    xob_meta(f"Glass_Mosque_{kind}", "Mosque_01_Glass", GLASS_EMAT)
    xob_meta(f"Glass_Mosque_{kind}_dst", "Mosque_01_Glass", GLASS_EMAT)
    gp = f"{WIN}/Glass_Mosque_{kind}.et"; wp = f"{WIN}/Win_Mosque_{kind}.et"
    open(gp, "w", newline="\n").write(f'''GenericEntity : "{{86834A0D5920F32F}}Prefabs/Structures/Core/DestructibleGlass_Base.et" {{
 ID "{G(kind + '.glass.id')}"
 components {{
  MeshObject "{{51C4DA208DB0E200}}" {{
   Object "{{{G(f'Glass_Mosque_{kind}.xob')}}}{WIN}/Glass_Mosque_{kind}.xob"
  }}
  RigidBody "{{51C4DA2091875CD5}}" {{
   ResponseIndex "TinyDestructible"
  }}
  SCR_DestructionMultiPhaseComponent "{{51C4DA20F6C21A24}}" {{
   m_aDamagePhases {{
    SCR_DamagePhaseData "{{52B6E4A66D596523}}" {{
     m_PhaseModel "{{{G(f'Glass_Mosque_{kind}_dst.xob')}}}{WIN}/Glass_Mosque_{kind}_dst.xob"
    }}
   }}
  }}
 }}
}}''')
    et_meta(gp, f"Glass_{kind}.et")
    open(wp, "w", newline="\n").write(f'''Building {{
 ID "{G(kind + '.win.id')}"
 components {{
  MeshObject "{{{G(kind + '.win.mo')}}}" {{
   Object "{{{G(f'Win_Mosque_{kind}.xob')}}}{WIN}/Win_Mosque_{kind}.xob"
  }}
  RigidBody "{{{G(kind + '.win.rb')}}}" {{
   ModelGeometry 1
   Static 1
  }}
 }}
 {{
  GenericEntity : "{{{G(f'Glass_{kind}.et')}}}{gp}" {{
   ID "{G(kind + '.win.child')}"
  }}
 }}
}}''')
    et_meta(wp, f"Win_{kind}.et")
json.dump(guids, open(GFILE, "w"), indent=1)

# ---- hall prefab: windows as instances ----
CARPET_GUID = re.search(r'Name "\{([0-9A-F]{16})\}', open(ROOT + "/Mosque_01_CarpetFloor.xob.meta", encoding="utf-8").read()).group(1)   # generated by Workbench
panes = json.load(open(sys.argv[1]))
rng2 = random.Random(20251025)
def i2(): return "".join(rng2.choice("0123456789ABCDEF") for _ in range(16))
out = ['GenericEntity {', ' ID "75A70139AF7B1025"', ' components {', '  MeshObject "{E310B743801FA6F1}" {',
       '   Object "{16C11A3943994961}Prefabs/Structures/Mosque_01/Mosque_01.xob"', '  }', '  RigidBody "{1CF94F20E788D787}" {',
       '   LayerPreset "BuildingFireView"', '   SimState Collision', '   ModelGeometry 1', '  }', ' }', ' coords 0 0 0', ' {',
       '  GameEnvironmentProbeEntity : "{565470F7BA530E0D}Prefabs/Structures/Core/ProbeHouse_Base.et" {', '   ID "D40CCA85F0F54F30"', '   coords 0 2.8 0', '  }',
       ]
CARPET = '{4DBC98809F18079A}Prefabs/Props/Furniture/Carpet_03_green_mosque.et'        # vanilla carpet (user's copy)
DOOR_R = '{06E20E31504A8381}Prefabs/Structures/BuildingParts/Doors/Door_ChurchSmall_E_01_right_EXT_COV_mosque.et'   # mirrored leaf: hinge on the right, opens like the left one (both prefabs extend +x from their hinge; the church socket for the right leaf is rotated 180)
DOOR = '{8A0A9BE2DAAC5D51}Prefabs/Structures/BuildingParts/Doors/Door_ChurchSmall_E_01_left_EXT_COV_mosque.et'
def ent(prefab, x, y, z, yaw=0.0, scale=1.0, cls='GenericEntity'):
    L = [f'  {cls} : "{prefab}" {{', f'   ID "{i2()}"', f'   coords {x:.3f} {y:.3f} {z:.3f}']
    if yaw: L.append(f'   angles 0 {yaw % 360:.2f} 0')
    if scale != 1.0: L.append(f'   scale {scale:.3f}')
    return L + ['  }']
CARPET_SCALE = float(os.environ.get('CARPET_SCALE', '1'))
for gx in (-1, 0, 1):                         # hall: 3 x 3 carpets (Blender y = Enfusion z)
    for gy in (-1, 0, 1): out += ent(CARPET, gx * 2.2 * CARPET_SCALE, 0.945, gy * 3.2 * CARPET_SCALE, 0, CARPET_SCALE)
out += ent(CARPET, 0, 0.96, 11.0, 90, CARPET_SCALE)                                   # porch
DOOR_S = float(os.environ.get('DOOR_SCALE', '1.14'))                                   # arch opening is 2.3 m wide x 2.9 m high; leaf is ~1.0 m wide, so 1.14 -> the two leaves meet at x=0 without overlapping (overlap z-fought)
out += ent(DOOR, -1.15, 0.95, 8.68, 0, DOOR_S) + ent(DOOR_R, 1.15, 0.95, 8.68, 180, DOOR_S)   # entrance leaves (hinges at the frame)
for kind, bx, by, bz, rz in panes:
    out += [f'  Building : "{{{G(f"Win_{kind}.et")}}}{WIN}/Win_Mosque_{kind}.et" {{', f'   ID "{i2()}"', f'   coords {bx:.3f} {bz:.3f} {by:.3f}', f'   angles 0 {(-rz) % 360:.2f} 0', '  }']
out += [' }', '}']
open(ROOT + ".et", "w", newline="\n").write("\n".join(out))
print("windows written:", len(panes))
